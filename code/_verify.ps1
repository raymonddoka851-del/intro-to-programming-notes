# ============================================================================
#  _verify.ps1 - compile and run every C example.
#
#  Compiler flags: -std=c11 -Wall -Wextra -Werror
#  Each program is run with a fixed input so the result is repeatable.
#  Writes code/VERIFIED_OUTPUT.md with the real output of every program.
#
#  Usage (from the Revision Pack folder):
#      powershell -NoProfile -ExecutionPolicy Bypass -File ".\code\_verify.ps1"
#
#  Exit code 0 = every program compiled cleanly and ran without crashing.
# ============================================================================

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$CodeRoot = $PSScriptRoot
$PackRoot = Split-Path -Parent $CodeRoot
$Gcc = Join-Path $env:LOCALAPPDATA 'mingw64\mingw64\bin\gcc.exe'
$Work = Join-Path $env:TEMP 'csc112-verify'

if (-not (Test-Path -LiteralPath $Gcc)) {
    Write-Host "gcc not found at $Gcc" -ForegroundColor Red
    exit 1
}

if (Test-Path -LiteralPath $Work) { Remove-Item -LiteralPath $Work -Recurse -Force }
New-Item -ItemType Directory -Force -Path $Work | Out-Null

# Fixed input for each program. Programs with no scanf entry get no input.
$Inputs = @{
    'add_two.c'        = "7 5`n"
    'area_circle.c'    = "2`n"
    'largest3.c'       = "3 9 4`n"
    'grade_switch.c'   = "B`n"
    'sum_n.c'          = "5`n"
    'factorial.c'      = "5`n"
    'reverse_number.c' = "1234`n"
    'prime_check.c'    = "97`n"
    'star_pyramid.c'   = "5`n"
    'functions.c'      = "5`n"
    'array_stats.c'    = "5`n1 -2 3 4 5`n"
    'bubble_sort.c'    = "5`n5 1 4 2 3`n"
    'struct_student.c' = "2`nAlice 20 85.5`nBob 21 72`n"
    'file_records.c'   = "2`nAlice 20 85.5`nBob 21 72`n"
    'string_demo.c'    = "Never odd or even`n"
}

$rows = New-Object 'System.Collections.Generic.List[object]'
$failed = 0

Push-Location $Work
try {
    foreach ($src in (Get-ChildItem -LiteralPath $CodeRoot -Filter *.c | Sort-Object Name)) {
        $name = $src.Name
        $exe  = Join-Path $Work ($src.BaseName + '.exe')
        Write-Host ("Compiling {0}" -f $name) -ForegroundColor Cyan
        $compile = & $Gcc -std=c11 -Wall -Wextra -Werror $src.FullName -o $exe 2>&1 | Out-String
        $compileCode = $LASTEXITCODE

        if ($compileCode -ne 0) {
            $failed++
            $rows.Add([pscustomobject]@{
                Name = $name; Compile = 'FAIL'; Exit = '-'; Input = ''
                Output = ($compile.Trim()); Flags = "-Wall -Wextra -Werror"
            })
            Write-Host ("  compile FAILED`n{0}" -f $compile) -ForegroundColor Red
            continue
        }

        $inputText = if ($Inputs.ContainsKey($name)) { $Inputs[$name] } else { '' }
        if ($inputText) {
            $output = $inputText | & $exe 2>&1 | Out-String
        } else {
            $output = & $exe 2>&1 | Out-String
        }
        $runCode = $LASTEXITCODE
        if ($runCode -ne 0) { $failed++ }

        $rows.Add([pscustomobject]@{
            Name = $name; Compile = 'ok'; Exit = $runCode; Input = $inputText.TrimEnd()
            Output = $output.TrimEnd(); Flags = "-Wall -Wextra -Werror"
        })
        Write-Host ("  compile ok, run exit {0}" -f $runCode) -ForegroundColor $(if ($runCode -eq 0) { 'Green' } else { 'Red' })
    }
}
finally {
    Pop-Location
}

# ---------------------------------------------------------------- report ----

$md = New-Object System.Text.StringBuilder
[void]$md.Append("# Verified program output`n`n")
[void]$md.Append("Generated by ``code/_verify.ps1``. Every program below was compiled with ``gcc -std=c11 -Wall -Wextra -Werror`` and run with the input shown. This is the real output of this machine, not a hand-written sample.`n`n")
[void]$md.Append("| Program | Compile | Exit |`n|---|---|---|`n")
foreach ($r in $rows) {
    [void]$md.Append("| ``$($r.Name)`` | $($r.Compile) | $($r.Exit) |`n")
}
[void]$md.Append("`n")

foreach ($r in $rows) {
    [void]$md.Append("## $($r.Name)`n`n")
    [void]$md.Append("Compile: **$($r.Compile)**. Exit code: **$($r.Exit)**.`n`n")
    if ($r.Compile -ne 'ok') {
        [void]$md.Append("``````text`n$($r.Output)`n```````n`n")
        continue
    }
    [void]$md.Append('Input: ')
    if ($r.Input) { [void]$md.Append("``" + ($r.Input -replace "`n", ' \n ') + "``") }
    else { [void]$md.Append('*(none)*') }
    [void]$md.Append("`n`n``````text`n$($r.Output)`n```````n`n")
}

[System.IO.File]::WriteAllText((Join-Path $CodeRoot 'VERIFIED_OUTPUT.md'), $md.ToString(),
    (New-Object System.Text.UTF8Encoding($false)))

Write-Host ''
Write-Host ("Programs: {0}   Failures: {1}" -f $rows.Count, $failed) -ForegroundColor $(if ($failed -eq 0) { 'Green' } else { 'Red' })
Write-Host ("Report: {0}" -f (Join-Path $CodeRoot 'VERIFIED_OUTPUT.md'))
if ($failed -eq 0) { exit 0 } else { exit 1 }
